import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import os from 'node:os';
import path from 'node:path';
import { createRequire } from 'node:module';
const require = createRequire(import.meta.url);
const modulePath = process.env.PLAYWRIGHT_MODULE || path.join(os.homedir(),'.cache/codex-runtimes/codex-primary-runtime/dependencies/node/node_modules/playwright');
const { chromium } = require(modulePath);
const browser = await chromium.launch({headless:true, channel:'msedge'});
const context = await browser.newContext({viewport:{width:1440,height:1000},reducedMotion:'reduce'});
const page = await context.newPage();
const errors=[];page.on('pageerror',e=>errors.push(e.message));
const results=[];
const check=(name,condition)=>{assert.ok(condition,name);results.push(name);};
const read=()=>page.evaluate(()=>window.arrowSpaceShiftTest.read());
const advance=seconds=>page.evaluate(n=>window.arrowSpaceShiftTest.advance(n),seconds);
await fs.mkdir('reports',{recursive:true});
try {
  await page.goto('http://127.0.0.1:4177/?test=1');
  check('Game title uses Arrow Space Shift',(await page.title()).includes('Arrow Space Shift'));
  check('Timing course is the default',(await read()).mode==='timing');
  check('Course overlay hides the unrelated quick-start button',!(await page.locator('#practice').isVisible()));
  await page.screenshot({path:'reports/timing-ready.png',fullPage:true});
  await page.setViewportSize({width:390,height:844});
  check('Compact timing course has no horizontal overflow',await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
  await page.screenshot({path:'reports/timing-compact.png',fullPage:true});
  await page.setViewportSize({width:1440,height:1000});
  await page.selectOption('#mode','space');
  await page.getByRole('button',{name:'Start space test',exact:true}).click();
  check('Space test starts without combat', (await read()).mode==='space');
  await page.keyboard.down('ShiftLeft');
  check('Left Shift creates one fold', (await read()).fields.length===1);
  await page.keyboard.down('ShiftLeft');
  check('Held Shift does not repeat folds', (await read()).fields.length===1);
  await page.keyboard.up('ShiftLeft');
  const entered=await advance(2);
  check('Constant thrust reaches a compressed region', entered.localFactor===2 && entered.thrust===90 && entered.z>180);
  const time=entered.time,z=entered.z;
  await page.keyboard.press('ShiftRight');
  const unfolded=await read();
  check('Right Shift restores the metric without reversing position or time',unfolded.fields.length===0 && unfolded.z===z && unfolded.time===time && unfolded.localFactor===1);
  await page.keyboard.down('ArrowRight');await advance(0.5);await page.keyboard.up('ArrowRight');
  check('Real arrow input steers the ship',(await read()).x>100);
  await page.keyboard.down('Space');await advance(0.5);await page.keyboard.up('Space');
  check('Space fires shots',(await read()).shotCount>0);
  await page.keyboard.press('KeyP');const paused=await read();await advance(2);
  check('Pause blocks simulation advancement',(await read()).time===paused.time && paused.phase==='paused');
  await page.getByRole('button',{name:'Resume flight',exact:true}).click();
  let removedKeysWork=false;
  for(const key of ['KeyW','KeyA','KeyS','KeyD','KeyF','KeyV']){
    const before=await read();await page.keyboard.down(key);const after=await advance(0.1);await page.keyboard.up(key);
    removedKeysWork ||= after.x!==before.x || after.thrust!==90 || after.fields.length!==before.fields.length;
  }
  check('WASD and F/V have no gameplay action',!removedKeysWork);
  await page.keyboard.down('ArrowUp');const fast=await advance(0.1);await page.keyboard.up('ArrowUp');
  await page.keyboard.down('ArrowDown');const slow=await advance(0.1);await page.keyboard.up('ArrowDown');
  check('Up and Down control thrust',Math.abs(fast.thrust-126)<1e-8 && Math.abs(slow.thrust-54)<1e-8);
  await page.keyboard.press('ShiftLeft');
  await page.screenshot({path:'reports/desktop-fold.png',fullPage:true});
  await page.getByRole('button',{name:'Restart',exact:true}).click();
  const reset=await read();
  check('Restart clears the full flight and fold display',reset.time===0 && reset.z===0 && reset.hull===5 && reset.fields.length===0 && reset.shotCount===0 && (await page.locator('#fold-stack').innerText()).includes('No active fields.'));
  await page.getByRole('button',{name:'Start reference route',exact:true}).click();
  await advance(7);await page.keyboard.press('KeyP');
  check('Combat mode runs',(await read()).mode==='flight' && (await read()).time>6);
  await page.getByRole('button',{name:'Resume flight',exact:true}).click();
  await page.keyboard.press('ShiftLeft');
  await page.screenshot({path:'reports/combat.png',fullPage:true});
  await page.evaluate(()=>window.dispatchEvent(new Event('blur')));
  check('Focus loss pauses flight',(await read()).phase==='paused');
  await page.getByRole('button',{name:'Resume flight',exact:true}).click();
  await page.evaluate(()=>window.arrowSpaceShiftTest.start('space'));
  const finish=await advance(95);
  check('A complete route reaches the result screen',finish.phase==='won' && finish.z===8400 && await page.getByRole('heading',{name:'Transit complete.',exact:true}).isVisible());
  await page.setViewportSize({width:390,height:844});
  await page.getByRole('button',{name:'Fly again',exact:true}).click();
  await page.locator('#fold').click();
  check('Fold display does not act as another control',(await read()).fields.length===0);
  await page.keyboard.press('ShiftLeft');
  check('Only Left Shift adds a fold',(await read()).fields.length===1);
  await page.keyboard.press('ShiftRight');
  check('Only Right Shift removes a fold',(await read()).fields.length===0);
  const canvas=page.locator('canvas');const box=await canvas.boundingBox();
  await page.mouse.move(box.x+box.width/2,box.y+box.height/2);await page.mouse.down();
  await page.mouse.move(box.x+box.width*0.8,box.y+box.height/2);await advance(0.5);await page.mouse.up();
  check('Pointer dragging does not replace arrow controls',(await read()).x===0);
  const bounds=await page.evaluate(()=>({page:document.documentElement.scrollWidth,width:innerWidth}));
  check('Compact layout has no horizontal overflow',bounds.page<=bounds.width);
  await page.screenshot({path:'reports/compact.png',fullPage:true});
  await page.setViewportSize({width:320,height:740});
  check('320 px layout has no horizontal overflow',await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
  await page.setViewportSize({width:1440,height:1000});
  await page.evaluate(()=>window.arrowSpaceShiftTest.loadShotTrial());
  const openStart=await read();const openEnd=await advance(0.1);
  await page.evaluate(()=>window.arrowSpaceShiftTest.loadShotTrial());
  await page.keyboard.press('ShiftLeft');
  const foldStart=await read();const foldEnd=await advance(0.1);
  const outgoing=s=>s.projectiles.player[0].distance;
  const incoming=s=>s.projectiles.enemy[0].distance;
  check('Fold increases outgoing shot motion in display space',outgoing(foldEnd)-outgoing(foldStart)>1.8*(outgoing(openEnd)-outgoing(openStart)));
  check('Fold increases incoming shot motion in display space',incoming(foldStart)-incoming(foldEnd)>1.5*(incoming(openStart)-incoming(openEnd)));
  check('Both shot types report the fold boost',foldEnd.projectiles.player[0].speedFactor===2 && foldEnd.projectiles.enemy[0].speedFactor===2);
  await page.keyboard.press('ShiftRight');const release=await read();const released=await advance(0.1);
  check('Unfold restores outgoing and incoming shot speed',released.projectiles.player[0].speedFactor===1 && released.projectiles.enemy[0].speedFactor===1 && outgoing(released)-outgoing(release)<outgoing(foldEnd)-outgoing(foldStart));
  await page.screenshot({path:'reports/projectile-trial.png',fullPage:true});
  await page.getByRole('button',{name:'Restart',exact:true}).click();
  await page.selectOption('#mode','timing');
  await page.getByText('Playtest notes and results',{exact:true}).click();
  await page.fill('#prediction','Automated fixture: fold for the opening, then unfold to escape.');
  async function playCourse(bonusEnabled){
    await page.locator('#bonus-enabled').setChecked(bonusEnabled);
    check('Score rule text matches the selected condition',(await page.locator('#bonus-rule').innerText())===(bonusEnabled?'Each fold at the target adds 50 points to a kill.':'A kill gives 100 points in folded or open space.'));
    await page.getByRole('button',{name:'Start encounter 1',exact:true}).click();
    check(`Countdown holds the encounter clock (${bonusEnabled?'bonus':'no bonus'})`,(await read()).time===0 && (await read()).countdown===2);
    await page.keyboard.down('Space');await page.keyboard.press('ShiftLeft');await advance(2.8);await page.keyboard.up('Space');
    check(`Outgoing encounter clears (${bonusEnabled?'bonus':'no bonus'})`,(await read()).phase==='won' && (await read()).score===(bonusEnabled?150:100));
    check('Bonus setting stays fixed during the course',await page.locator('#bonus-enabled').isDisabled());
    await page.getByRole('button',{name:'Start encounter 2',exact:true}).click();
    check('Defensive encounter starts folded',(await read()).fields.length===1 && (await read()).enemyShotCount===1);
    await page.keyboard.press('ShiftRight');await page.keyboard.down('ArrowRight');await advance(4.8);await page.keyboard.up('ArrowRight');
    check(`Defensive encounter clears (${bonusEnabled?'bonus':'no bonus'})`,(await read()).phase==='won' && (await read()).hull===5);
    await page.getByRole('button',{name:'Start encounter 3',exact:true}).click();
    await page.keyboard.down('Space');await page.keyboard.press('ShiftLeft');await advance(2.8);await page.keyboard.up('Space');
    check('Combined target triggers a visible guard salvo',(await read()).encounter.hit && (await read()).enemyShotCount===1);
    if(bonusEnabled)await page.screenshot({path:'reports/timing-combined.png',fullPage:true});
    await page.keyboard.press('ShiftRight');await page.keyboard.down('ArrowRight');await advance(3);await page.keyboard.up('ArrowRight');
    check(`Combined encounter clears (${bonusEnabled?'bonus':'no bonus'})`,(await read()).phase==='won' && (await read()).hull===5);
    check('Course completion offers a replay',await page.getByRole('button',{name:'Repeat course',exact:true}).isVisible());
  }
  await playCourse(false);
  const without=await page.evaluate(()=>window.arrowSpaceShift.results().slice(-3));
  await page.getByRole('button',{name:'Restart',exact:true}).click();
  await playCourse(true);
  const withBonus=await page.evaluate(()=>window.arrowSpaceShift.results().slice(-3));
  check('Matched score versions preserve timing and hull',withBonus.every((r,i)=>r.time===without[i].time && r.hull===without[i].hull && r.result===without[i].result));
  await page.fill('#explanation','Automated fixture only. This is not a player observation.');
  const downloadWait=page.waitForEvent('download');await page.getByRole('button',{name:'Save test results',exact:true}).click();
  const download=await downloadWait;const exported=JSON.parse(await fs.readFile(await download.path(),'utf8'));
  check('Results export retains options, actions, and separate notes',exported.game==='Arrow Space Shift' && exported.attempts.at(-1).events.some(e=>e.type==='unfold') && exported.attempts.at(-1).explanation.startsWith('Automated fixture') && exported.attempts.at(-1).prediction.startsWith('Automated fixture'));
  await page.goto('http://127.0.0.1:4177/reference/v0.2/?test=1');
  await page.getByRole('button',{name:'Start flight',exact:true}).click();
  check('Preserved v0.2 reference remains playable',await page.evaluate(()=>window.foldspaceTest.advance(0.25).z>0));
  await page.goto('http://127.0.0.1:4177/');
  await page.selectOption('#mode','space');
  await page.getByRole('button',{name:'Start space test',exact:true}).click();
  await page.waitForTimeout(1000);
  const real=await page.evaluate(()=>window.arrowSpaceShift.read());
  check('Normal animation loop advances the flight',real.phase==='running' && real.time>0.3 && real.z>20);
  check('Fixture controls are absent from the normal page',await page.evaluate(()=>!window.arrowSpaceShiftTest));
  check('No browser runtime errors',errors.length===0);
  await fs.writeFile('reports/browser-results.json',JSON.stringify({browser:'Microsoft Edge, headless',version:browser.version(),checks:results.length,results,errors},null,2)+'\n');
  console.log(JSON.stringify({checks:results.length,results,errors},null,2));
} finally { await browser.close(); }
